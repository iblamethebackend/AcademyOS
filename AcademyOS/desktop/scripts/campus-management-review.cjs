const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {initialState}=require('../src/lib/model.ts');
const {saveCampus,saveCampusWithInCharge,removeCampus,validCampusConfiguration,validCampusPhoto}=require('../src/lib/campuses.ts');
let state=structuredClone(initialState);
assert.equal(validCampusConfiguration(state),true,'Old campuses remain compatible');
const original=structuredClone(state);
state=saveCampus(state,{...state.campuses[0],address:'10 Main Road, Bengaluru',inChargeId:'m1',staffIds:['m2'],studentIds:['s1'],photo:{id:'photo-1',name:'main.png',size:100,type:'image/png',path:'greenfield/c1/photo-1.png',storage:'local'}});
assert.deepEqual(state.campuses[0].staffIds,['m2','m1'],'In-charge is automatically included in campus staff');
state=saveCampus(state,{id:'east',name:'East campus',city:'Delhi',code:'east',address:'20 East Road, Delhi',inChargeId:'m2',staffIds:['m2'],studentIds:['s2']});
state=saveCampus(state,{id:'west',name:'West campus',city:'Pune',code:'west',address:'30 West Road, Pune',inChargeId:'m1',staffIds:['m1'],studentIds:['s1']});
assert.equal(state.campuses.length,4);
assert.equal(state.campuses.find(c=>c.id==='east').code,'EAST');
assert.equal(state.campuses[0].photo.name,'main.png');
assert.deepEqual(state.campuses[0].studentIds,['s1']);
assert.deepEqual(state.campuses.find(c=>c.id==='east').studentIds,['s2']);
assert.equal(validCampusConfiguration(state),true,'People can be mapped to multiple campuses');
assert.deepEqual(original,initialState,'Campus edits must not mutate the original workspace');
assert.throws(()=>saveCampus(state,{id:'duplicate',name:'Other',city:'Delhi',code:'main',address:'10 Other Road'}),/already used/);
assert.throws(()=>saveCampus(state,{id:'missing',name:'Other',city:'Delhi',code:'OT',address:''}),/address/);
const withCampus=campus=>({...state,campuses:[campus,...state.campuses.slice(1)]});
assert.equal(validCampusConfiguration(withCampus({...state.campuses[0],staffIds:['unknown']})),false);
assert.equal(validCampusConfiguration(withCampus({...state.campuses[0],studentIds:['unknown']})),false);
assert.equal(validCampusConfiguration(withCampus({...state.campuses[0],staffIds:['m1','m1']})),false);
assert.equal(validCampusConfiguration(withCampus({...state.campuses[0],staffIds:['m2']})),false,'In-charge must belong to campus staff');
assert.throws(()=>removeCampus(state,'c1'),/primary/);
const removed=removeCampus(state,'east');
assert.deepEqual(removed.members,state.members);
assert.deepEqual(removed.students,state.students);
assert.deepEqual(removed.campuses.find(c=>c.id==='west'),state.campuses.find(c=>c.id==='west'));
assert.equal(removed.campuses.some(c=>c.id==='east'),false);
assert.equal(validCampusPhoto({name:'campus.jpg',size:5*1024*1024}),true);
assert.equal(validCampusPhoto({name:'campus.png',size:0}),false);
assert.equal(validCampusPhoto({name:'campus.svg',size:100}),false);
assert.equal(validCampusPhoto({name:'campus.png',size:5*1024*1024+1}),false);
console.log('PASS: legacy campuses, independent multi-campus assignments, in-charge membership, photos, duplicate codes, references, deletion guards and immutable roster preservation.');

const person={id:'new-in-charge',name:'  Riya Sharma  ',email:'  RIYA@example.com '};
const withPerson=saveCampusWithInCharge(original,{...original.campuses[0],address:'10 Main Road'},person);
assert.equal(withPerson.members.length,original.members.length+1);
assert.equal(original.members.length,initialState.members.length,'Preparing a new in-charge must not mutate existing records');
assert.equal(withPerson.members.at(-1).name,'Riya Sharma');
assert.equal(withPerson.members.at(-1).email,'riya@example.com');
assert.equal(withPerson.members.at(-1).role,'Campus in-charge');
assert.equal(withPerson.campuses[0].inChargeId,person.id);
assert.ok(withPerson.campuses[0].staffIds.includes(person.id));
assert.equal(validCampusConfiguration(withPerson),true);
assert.throws(()=>saveCampusWithInCharge(withPerson,{...withPerson.campuses[1],address:'20 North Road'},{...person,id:'another'}),/already belongs/);
assert.throws(()=>saveCampusWithInCharge(original,{...original.campuses[0],address:'10 Main Road'},{...person,email:'invalid'}),/valid email/);
assert.throws(()=>saveCampusWithInCharge(original,{...original.campuses[0],address:''},person),/address/);
const reused=saveCampusWithInCharge(withPerson,{...withPerson.campuses[1],address:'20 North Road',inChargeId:person.id});
assert.equal(reused.members.length,withPerson.members.length);
assert.equal(reused.campuses[1].inChargeId,person.id);
assert.equal(reused.campuses[0].inChargeId,person.id);
console.log('PASS: new in-charge creation is atomic, validates details, prevents duplicate emails and supports reuse across campuses.');
