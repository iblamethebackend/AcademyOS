const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {invitationDepartment}=require('../src/lib/invitation-department.ts');
const {validDepartmentConfiguration}=require('../src/lib/departments.ts');
const source=[];
const suggested=invitationDepartment(source,'suggested:Science');
assert.equal(source.length,0,'Do not change school departments until the invitation is saved');
assert.equal(suggested.departments.length,1);
assert.equal(suggested.departments[0].name,'Science');
assert.equal(suggested.departmentId,suggested.departments[0].id);
assert.equal(validDepartmentConfiguration({departments:suggested.departments,members:[{departmentId:suggested.departmentId}]}),true);
const reused=invitationDepartment(suggested.departments,suggested.departmentId);
assert.equal(reused.departments.length,1);
assert.equal(reused.departmentId,suggested.departmentId);
const differentCase=[{id:'science',name:'  SCIENCE ',description:''}];
assert.equal(invitationDepartment(differentCase,'suggested:Science').departmentId,'science');
assert.equal(invitationDepartment(differentCase,'').departmentId,undefined);
assert.throws(()=>invitationDepartment([],'missing-id'),/no longer available/);
assert.throws(()=>invitationDepartment([],'suggested:Unknown'),/from the list/);
assert.throws(()=>invitationDepartment([],'suggested:__proto__'),/from the list/);
const full=Array.from({length:100},(_,i)=>({id:'d'+i,name:'Team '+i,description:''}));
assert.throws(()=>invitationDepartment(full,'suggested:Science'),/limit/);
assert.equal(invitationDepartment(full,'d0').departmentId,'d0');
console.log('PASS: empty-school suggestions, assignment references, no duplicate departments, cancelled/stale choices and department limits.');
