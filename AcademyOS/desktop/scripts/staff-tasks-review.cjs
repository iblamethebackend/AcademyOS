const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {validStaffTaskConfiguration,validSubmissionFile,validTaskDate,schoolDate,staffActivity,taskOverdue,maxSubmissionBytes,assignStaffTask,matchesTaskDepartment}=require('../src/lib/staff-tasks.ts');
const task={id:'task-1',memberId:'member-1',memberName:'Test Teacher',title:'Weekly record',description:'Upload your completed record.',dueDate:'2026-11-12',createdAt:'2026-11-10T10:00:00.000Z',status:'Assigned',submissions:[]};
const submission={id:'submission-1',submittedAt:'2026-11-13T10:00:00.000Z',note:'Weekly record received.',recordedBy:'School owner'};
assert.equal(validStaffTaskConfiguration({}),true,'Old workspaces remain compatible');
assert.equal(validStaffTaskConfiguration({staffTasks:[task]}),true);
assert.equal(validStaffTaskConfiguration({staffTasks:[{...task,status:'Completed'}]}),false,'An assignment alone is not completed work');
assert.equal(validStaffTaskConfiguration({staffTasks:[{...task,status:'Submitted'}]}),false);
assert.equal(validStaffTaskConfiguration({staffTasks:[task,task]}),false);
assert.equal(validStaffTaskConfiguration({staffTasks:[{...task,submissions:[{...submission,note:''}]}]}),false);
assert.equal(validTaskDate('2026-02-30'),false);
assert.equal(validTaskDate('2026-11-13'),true);
assert.equal(taskOverdue(task,'2026-11-13'),true);
assert.equal(taskOverdue(task,'2026-11-12'),false);
const completed={...task,status:'Completed',completedAt:'2026-11-13T11:00:00Z',submissions:[submission]};
assert.equal(validStaffTaskConfiguration({staffTasks:[completed]}),true);
assert.equal(taskOverdue(completed,'2026-11-13'),false);
const stats=staffActivity([completed],'member-1',Date.parse('2026-11-14T10:00:00Z'));
assert.equal(stats.active,true);assert.equal(stats.completed,1);assert.equal(stats.submissions,1);
assert.equal(staffActivity([completed],'another-member').submissions,0);
assert.equal(staffActivity([completed],'member-1',Date.parse('2026-11-22T10:00:00Z')).active,false);
assert.equal(staffActivity([task],'member-1').active,false,'Active account is not evidence of submissions');
assert.equal(schoolDate('Asia/Kolkata',new Date('2026-11-12T23:00:00Z')),'2026-11-13');
assert.equal(schoolDate('America/New_York',new Date('2026-11-12T23:00:00Z')),'2026-11-12');
assert.equal(validSubmissionFile({name:'record.csv',size:1024}),true);
assert.equal(validSubmissionFile({name:'record.html',size:1024}),false);
assert.equal(validSubmissionFile({name:'record.pdf',size:maxSubmissionBytes+1}),false);
assert.equal(validSubmissionFile({name:'record.pdf',size:0}),false);
console.log('PASS: task validation, completion evidence, staff activity, overdue dates, school timezones and upload limits.');

const {initialState}=require('../src/lib/model.ts');
const {validDepartmentConfiguration}=require('../src/lib/departments.ts');
const school=structuredClone(initialState),before=structuredClone(school);
const assignment={id:'new-task',memberId:'m2',title:'Submit records',description:'Weekly records',dueDate:'2026-11-20',createdAt:'2026-11-14T10:00:00Z'};
const staff={id:'new-staff',name:'  Riya Shah ',email:' RIYA@example.com ',role:'Teacher',departmentId:'suggested:Science'};
const assigned=assignStaffTask(school,assignment,staff);
assert.equal(assigned.members.length,school.members.length+1);
assert.equal(assigned.members.at(-1).email,'riya@example.com');
assert.equal(assigned.staffTasks[0].memberId,staff.id);
assert.equal(assigned.staffTasks[0].memberName,'Riya Shah');
assert.equal(assigned.departments[0].name,'Science');
assert.equal(assigned.members.at(-1).departmentId,assigned.departments[0].id);
assert.equal(validStaffTaskConfiguration(assigned),true);
assert.equal(validDepartmentConfiguration(assigned),true);
assert.deepEqual(school,before,'Preparing staff and task must not mutate saved school data');
assert.throws(()=>assignStaffTask(school,assignment,{...staff,email:'ananya@greenfield.example'}),/already in your school team/);
assert.throws(()=>assignStaffTask(school,assignment,{...staff,email:'invalid'}),/valid staff email/);
assert.throws(()=>assignStaffTask(school,{...assignment,title:''},staff),/task title/);
assert.throws(()=>assignStaffTask(school,assignment,{...staff,departmentId:'missing'}),/department/);
assert.throws(()=>assignStaffTask(school,assignment,{...staff,role:'Unknown'}),/staff role/);
const existing=assignStaffTask(assigned,{...assignment,id:'second-task',memberId:staff.id});
assert.equal(existing.members.length,assigned.members.length);
assert.equal(existing.staffTasks[0].memberId,staff.id);
assert.throws(()=>assignStaffTask(assigned,assignment),/already exists/);
console.log('PASS: new staff and task save together, department references are valid, duplicates/invalid data are rejected and existing staff are reused.');

const scienceId=assigned.departments[0].id;
assert.equal(matchesTaskDepartment(assigned,assigned.staffTasks[0],''),true);
assert.equal(matchesTaskDepartment(assigned,assigned.staffTasks[0],scienceId),true);
assert.equal(matchesTaskDepartment(assigned,assigned.staffTasks[0],'suggested:Science'),true);
assert.equal(matchesTaskDepartment(assigned,assigned.staffTasks[0],'suggested:Finance'),false);
assert.equal(matchesTaskDepartment(assigned,assigned.staffTasks[0],'__unassigned__'),false);
assert.equal(matchesTaskDepartment(school,{...task,memberId:'m1'},'__unassigned__'),true);
assert.equal(matchesTaskDepartment(school,{...task,memberId:'m1'},'suggested:Science'),false);
assert.deepEqual(school,before,'Department filtering must not create departments or change assignments');
console.log('PASS: department filters match current staff assignments, support unassigned staff and never create records.');

const {prepareStaffMember}=require('../src/lib/staff-members.ts');
const standalone=prepareStaffMember(school,{...staff,id:'standalone-staff'});
assert.equal(standalone.state.members.length,school.members.length+1);
assert.equal(standalone.state.staffTasks,school.staffTasks,'Adding staff alone must not create tasks');
assert.deepEqual(standalone.state.campuses,school.campuses);
assert.equal(standalone.member.id,'standalone-staff');
assert.equal(standalone.member.departmentId,standalone.state.departments[0].id);
assert.deepEqual(school,before);
assert.throws(()=>prepareStaffMember(standalone.state,{...staff,id:'duplicate-staff'}),/already in your school team/);
console.log('PASS: standalone staff creation persists the roster/department without creating a task or changing campus mappings.');
